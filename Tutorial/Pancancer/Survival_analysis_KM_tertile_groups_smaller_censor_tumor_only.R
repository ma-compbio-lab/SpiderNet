  colnames(HR_mat) <- TCGA_project_list
  rownames(pvalue_mat) <- MI_unique
  colnames(pvalue_mat) <- TCGA_project_list
  rownames(pvalue_mat_bettersurvival) <- MI_unique
  colnames(pvalue_mat_bettersurvival) <- TCGA_project_list
  rownames(pvalue_mat_worsesurvival) <- MI_unique
  colnames(pvalue_mat_worsesurvival) <- TCGA_project_list
  rownames(nestedLRT_chisq_mat) <- MI_unique
  colnames(nestedLRT_chisq_mat) <- TCGA_project_list
  rownames(nestedLRT_df_mat) <- MI_unique
  colnames(nestedLRT_df_mat) <- TCGA_project_list
  rownames(nestedLRT_pvalue_mat) <- MI_unique
  colnames(nestedLRT_pvalue_mat) <- TCGA_project_list

  ## ===============================
  ## Result matrices: unadjusted (NO covariates)
  ## ===============================
  HR_mat_unadj <- matrix(NA, nrow = length(MI_unique), ncol = length(TCGA_project_list))
  pvalue_mat_unadj <- matrix(NA, nrow = length(MI_unique), ncol = length(TCGA_project_list))
  pvalue_mat_unadj_bettersurvival <- matrix(NA, nrow = length(MI_unique), ncol = length(TCGA_project_list))
  pvalue_mat_unadj_worsesurvival  <- matrix(NA, nrow = length(MI_unique), ncol = length(TCGA_project_list))

  rownames(HR_mat_unadj) <- MI_unique
  colnames(HR_mat_unadj) <- TCGA_project_list
  rownames(pvalue_mat_unadj) <- MI_unique
  colnames(pvalue_mat_unadj) <- TCGA_project_list
  rownames(pvalue_mat_unadj_bettersurvival) <- MI_unique
  colnames(pvalue_mat_unadj_bettersurvival) <- TCGA_project_list
  rownames(pvalue_mat_unadj_worsesurvival) <- MI_unique
  colnames(pvalue_mat_unadj_worsesurvival) <- TCGA_project_list

  MI_decomposition_list <- list()
  module_score_list <- list()
  tumor_purity_source_list <- list()
  model_audit_list <- list()

  add_cohort <- function(project_cur, expr_cpm, MI_decomposition, common_samples,
                         coldata, idx_in_expr, expr, time_use, status_use) {
      module_score_df <- compute_marker_module_scores(
        expr_mat = expr_cpm,
        marker_list = marker_list
      )

      MI_decomposition_list[[project_cur]] <<- MI_decomposition
      module_score_list[[project_cur]] <<- module_score_df
  

      ## Align clinical covariates to common_samples once per project.
      coldata_common <- coldata[idx_in_expr, , drop = FALSE]
      rownames(coldata_common) <- colnames(expr)[idx_in_expr]
      coldata_common <- coldata_common[common_samples, , drop = FALSE]

      ## Tumor purity source is cohort-specific; record it for QC and reuse in
      ## all MI-specific Cox models for this project.
      tumor_purity_col_project <- if (isTRUE(If_add_tumor_purity)) {
        find_tumor_purity_column(coldata_common)
      } else {
        NA_character_
      }

      if (isTRUE(If_add_tumor_purity)) {
        if (is.na(tumor_purity_col_project)) {
          message("  -> Tumor purity requested but no usable tumor-purity column found for ", project_cur, ".")
        } else {
          message("  -> Tumor purity covariate for ", project_cur, ": ", tumor_purity_col_project)
        }
      }

      tumor_purity_source_list[[project_cur]] <<- summarize_tumor_purity_source(
        project_cur = project_cur,
        coldata_use = coldata_common,
        if_add = If_add_tumor_purity,
        source_col = tumor_purity_col_project
      )

      ## ===============================
      ## per-project result vectors
      ## ===============================
      HR_list <- rep(NA, length(MI_unique))
      pvalue_list <- rep(NA, length(MI_unique))
      pvalue_list_bettersurvival <- rep(NA, length(MI_unique))
      pvalue_list_worsesurvival <- rep(NA, length(MI_unique))

      ## Nested Cox LRT vectors for testing added value of score_scaled
      ## beyond clinical covariates + marker module scores.
      nestedLRT_chisq_list <- rep(NA, length(MI_unique))
      nestedLRT_df_list <- rep(NA, length(MI_unique))
      nestedLRT_pvalue_list <- rep(NA, length(MI_unique))
  
      HR_list_unadj <- rep(NA, length(MI_unique))
      pvalue_list_unadj <- rep(NA, length(MI_unique))
      pvalue_list_unadj_bettersurvival <- rep(NA, length(MI_unique))
      pvalue_list_unadj_worsesurvival <- rep(NA, length(MI_unique))

      for (i in seq_along(MI_unique)) {
        MI_cur <- MI_unique[i]
    
        ## -------------------------------
        ## score per sample
        ## -------------------------------
        if (MI_source_type == "Markergene") {
          Markergene_list <- unique(
            Phenotype_topgenes_summary$Genes[
              Phenotype_topgenes_summary$MI == MI_cur
            ]
          )
      
          expr_cpm_marker <- expr_cpm[rownames(expr_cpm) %in% Markergene_list, , drop = FALSE]
          if (nrow(expr_cpm_marker) == 0) next
      
          sample_score <- colMeans(expr_cpm_marker, na.rm = TRUE)
        } else {
          if (!(MI_cur %in% colnames(MI_decomposition))) next
          sample_score <- MI_decomposition[, MI_cur]
        }
    
        ## -------------------------------
        ## survival df (base)
        ## -------------------------------
        df_surv <- data.frame(
          sample  = common_samples,
          score   = as.numeric(sample_score),
          time    = as.numeric(time_use),
          status  = as.numeric(status_use),
          stringsAsFactors = FALSE
        )
    
        df_surv <- df_surv[complete.cases(df_surv[, c("score", "time", "status")]), , drop = FALSE]
        if (nrow(df_surv) < 10 || length(unique(df_surv$status)) < 2) next
        if (sum(df_surv$status == 1) < 3) next
    
        ## Scaled continuous MI strength for Cox regression.
        ## The High/Low group below is only used for KM visualization/log-rank.
        df_surv$score_scaled <- scale_score_for_cox(df_surv$score)
        if (all(is.na(df_surv$score_scaled))) next
    
        threshold_score <- choose_score_threshold(df_surv$score)
    
        if (MI_cur %in% km_mi_to_plot) {
          print(paste("Project:", project_cur, "MI:", MI_cur,
                      "Threshold used:", signif(threshold_score, 4)))
          print(summary(df_surv$score))
        }
    
        df_surv$group <- ifelse(
          df_surv$score >= threshold_score,
          "High", "Low"
        )
        ## The original binary-group gate is retained before continuous Cox fitting.
        df_surv$group <- factor(df_surv$group, levels = c("Low", "High"))
    
        if (length(unique(df_surv$group[!is.na(df_surv$group)])) < 2) next
    
        ## ===============================
        ## (A) Unadjusted Cox: scaled continuous MI strength only
        ##     HR = per 1 SD increase in MI strength
        ## ===============================
        fit_unadj <- try(coxph(Surv(time, status) ~ score_scaled, data = df_surv), silent = TRUE)
        if (!inherits(fit_unadj, "try-error")) {
          s_unadj <- summary(fit_unadj)
          if ("score_scaled" %in% rownames(s_unadj$coefficients)) {
            HR_list_unadj[i] <- s_unadj$coefficients["score_scaled", "exp(coef)"]
            pvalue_list_unadj[i] <- s_unadj$coefficients["score_scaled", "Pr(>|z|)"]
        
            z_unadj <- s_unadj$coefficients["score_scaled", "z"]
            pvalue_list_unadj_worsesurvival[i]  <- pnorm(z_unadj, lower.tail = FALSE)
            pvalue_list_unadj_bettersurvival[i] <- pnorm(z_unadj, lower.tail = TRUE)
          }
        }
    
        ## ===============================
        ## (B) Adjusted Cox using scaled continuous MI strength
        ##     + age/gender/tumor grade + marker module scores
        ##     HR = per 1 SD increase in MI strength
        ## ===============================
        df_surv2 <- data.frame(
          sample  = common_samples,
          score   = as.numeric(sample_score),
          time    = as.numeric(time_use),
          status  = as.numeric(status_use),
          stringsAsFactors = FALSE
        )
    
        df_surv2 <- add_covariate(df_surv2, coldata_common, "age_at_diagnosis", as_factor = FALSE)
        df_surv2 <- add_covariate(df_surv2, coldata_common, "gender", as_factor = TRUE)
        df_surv2 <- add_covariate(df_surv2, coldata_common, "tumor_grade", as_factor = TRUE)

        ## Optionally add tumor purity to BOTH nested Cox regression models.
        df_surv2 <- add_tumor_purity_covariate(
          df = df_surv2,
          coldata_use = coldata_common,
          if_add = If_add_tumor_purity,
          out_col = tumor_purity_covariate_name,
          source_col = tumor_purity_col_project
        )

        ## Add Invasion / Angiogenesis / EMT / Hypoxia module scores
        ## as additional continuous Cox covariates.
        df_surv2 <- add_module_scores_to_df(df_surv2, module_score_df)
    
        df_surv2 <- df_surv2[complete.cases(df_surv2), , drop = FALSE]
    
        if (nrow(df_surv2) < 10 || length(unique(df_surv2$status)) < 2) next
        if (sum(df_surv2$status == 1) < 3) next
    
        ## Scale MI strength after covariate filtering so the HR is per 1 SD
        ## within the samples actually used in the adjusted Cox model.
        df_surv2$score_scaled <- scale_score_for_cox(df_surv2$score)
        if (all(is.na(df_surv2$score_scaled))) next
    
        candidate_covars <- setdiff(colnames(df_surv2), c("sample", "score", "time", "status"))
        candidate_covars <- filter_usable_covars(df_surv2, candidate_covars)

        ## Model AB must include score_scaled.
        if (!("score_scaled" %in% candidate_covars)) next

        ## Nested Cox models:
        ##   Model A  = clinical covariates + optional tumor_purity + marker module scores
        ##   Model AB = Model A + score_scaled
        covars_AB <- candidate_covars
        covars_A <- setdiff(covars_AB, "score_scaled")

        if (length(covars_A) > 0) {
          cox_formula_A <- as.formula(
            paste("Surv(time, status) ~", paste(covars_A, collapse = " + "))
          )
        } else {
          ## Fallback if all adjustment covariates are unavailable/filtered out.
          ## This should be rare; normally covars_A includes clinical covariates
          ## and/or optional tumor_purity / Invasion / Angiogenesis / EMT / Hypoxia module scores.
          cox_formula_A <- as.formula("Surv(time, status) ~ 1")
        }

        cox_formula_AB <- as.formula(
          paste("Surv(time, status) ~", paste(covars_AB, collapse = " + "))
        )
    
        model_audit_list[[paste(project_cur, MI_cur, sep = "::")]] <<- data.frame(
          project = project_cur, MI = MI_cur, n = nrow(df_surv2),
          events = sum(df_surv2$status == 1),
          formula_A = paste(deparse(cox_formula_A), collapse = " "),
          formula_AB = paste(deparse(cox_formula_AB), collapse = " "),
          stringsAsFactors = FALSE
        )
        fit_A <- try(coxph(cox_formula_A, data = df_surv2), silent = TRUE)
        fit_adj <- try(coxph(cox_formula_AB, data = df_surv2), silent = TRUE)
        if (inherits(fit_adj, "try-error")) next

        ## Likelihood-ratio test for whether adding score_scaled improves model fit.
        if (!inherits(fit_A, "try-error")) {
          lrt_tab <- try(anova(fit_A, fit_adj, test = "LRT"), silent = TRUE)
          if (!inherits(lrt_tab, "try-error")) {
            lrt_res <- extract_nested_lrt(lrt_tab)
            nestedLRT_chisq_list[i] <- lrt_res$chisq
            nestedLRT_df_list[i] <- lrt_res$df
            nestedLRT_pvalue_list[i] <- lrt_res$pvalue
          }
        }
    
        s_adj <- summary(fit_adj)
    
        if ("score_scaled" %in% rownames(s_adj$coefficients)) {
          z_adj <- s_adj$coefficients["score_scaled", "z"]
          p_one_sided_worsesurvival  <- pnorm(z_adj, lower.tail = FALSE)
          p_one_sided_bettersurvival <- pnorm(z_adj, lower.tail = TRUE)
      
          HR_list[i] <- s_adj$coefficients["score_scaled", "exp(coef)"]
          pvalue_list[i] <- s_adj$coefficients["score_scaled", "Pr(>|z|)"]
          pvalue_list_bettersurvival[i] <- p_one_sided_bettersurvival
          pvalue_list_worsesurvival[i] <- p_one_sided_worsesurvival
        }
      }
      HR_mat[, project_cur] <<- HR_list
      pvalue_mat[, project_cur] <<- pvalue_list
      pvalue_mat_bettersurvival[, project_cur] <<- pvalue_list_bettersurvival
      pvalue_mat_worsesurvival[, project_cur] <<- pvalue_list_worsesurvival

      nestedLRT_chisq_mat[, project_cur] <<- nestedLRT_chisq_list
      nestedLRT_df_mat[, project_cur] <<- nestedLRT_df_list
      nestedLRT_pvalue_mat[, project_cur] <<- nestedLRT_pvalue_list
  
      HR_mat_unadj[, project_cur] <<- HR_list_unadj
      pvalue_mat_unadj[, project_cur] <<- pvalue_list_unadj
      pvalue_mat_unadj_bettersurvival[, project_cur] <<- pvalue_list_unadj_bettersurvival
      pvalue_mat_unadj_worsesurvival[, project_cur]  <<- pvalue_list_unadj_worsesurvival
  }

  finish <- function() {
    save(module_score_list, file = paste0(file_path_main, "TCGA_marker_module_score_list_", MI_type_addmodules, ".Rdata"))
    tumor_purity_source_df <- do.call(rbind, tumor_purity_source_list)
    write.csv(
      tumor_purity_source_df,
      file = paste0(file_path_main, "TCGA_tumor_purity_source_record_", MI_type_addmodules, ".csv"),
      row.names = FALSE
    )
    write.csv(HR_mat, file = paste0(file_path_main, "TCGA_MIs_HR_matrix_", MI_type_addmodules, ".csv"))
    write.csv(pvalue_mat, file = paste0(file_path_main, "TCGA_MIs_pvalue_matrix_", MI_type_addmodules, ".csv"))
    write.csv(pvalue_mat_bettersurvival, file = paste0(file_path_main, "TCGA_MIs_pvalue_bettersurvival_matrix_", MI_type_addmodules, ".csv"))
    write.csv(pvalue_mat_worsesurvival, file = paste0(file_path_main, "TCGA_MIs_pvalue_worsesurvival_matrix_", MI_type_addmodules, ".csv"))

    ## Nested Cox likelihood-ratio test outputs.
    ## P-value tests whether Model AB (= Model A + score_scaled) improves fit
    ## over Model A (= clinical covariates + marker module scores + optional tumor_purity).
    write.csv(nestedLRT_chisq_mat, file = paste0(file_path_main, "TCGA_MIs_nestedLRT_chisq_add_score_matrix_", MI_type_addmodules, ".csv"))
    write.csv(nestedLRT_df_mat, file = paste0(file_path_main, "TCGA_MIs_nestedLRT_df_add_score_matrix_", MI_type_addmodules, ".csv"))
    write.csv(nestedLRT_pvalue_mat, file = paste0(file_path_main, "TCGA_MIs_nestedLRT_pvalue_add_score_matrix_", MI_type_addmodules, ".csv"))

    write.csv(HR_mat_unadj, file = paste0(file_path_main, "TCGA_MIs_HR_matrix_unadjusted_", MI_type_addmodules, ".csv"))
    write.csv(pvalue_mat_unadj, file = paste0(file_path_main, "TCGA_MIs_pvalue_matrix_unadjusted_", MI_type_addmodules, ".csv"))
    write.csv(pvalue_mat_unadj_bettersurvival, file = paste0(file_path_main, "TCGA_MIs_pvalue_bettersurvival_matrix_unadjusted_", MI_type_addmodules, ".csv"))
    write.csv(pvalue_mat_unadj_worsesurvival, file = paste0(file_path_main, "TCGA_MIs_pvalue_worsesurvival_matrix_unadjusted_", MI_type_addmodules, ".csv"))
    if (length(model_audit_list) > 0) {
      write.csv(do.call(rbind, model_audit_list),
                file.path(file_path_main, "S27b_model_formulas_and_counts.csv"), row.names = FALSE)
    }
    write.csv(data.frame(setting = c("MI", "module_scores", "clinical_covariates", "include_tumor_purity", "HR_source"),
                         value = c("MI4", paste(names(marker_list), collapse = ";"),
                                   "age_at_diagnosis;gender;tumor_grade", as.character(If_add_tumor_purity), km_hr_path)),
              file.path(file_path_main, "S27b_settings.csv"), row.names = FALSE)
    scatter_result <- plot_nested_lrt(
      km_hr_path,
      paste0(file_path_main, "TCGA_MIs_nestedLRT_pvalue_add_score_matrix_", MI_type_addmodules, ".csv"),
      file_path_main
    )
    df_scatter <- scatter_result$scatter
    nestedLRT_pvalue_mat <- scatter_result$LRT_pvalue
    invisible(list(HR = HR_mat, LRT_pvalue = nestedLRT_pvalue_mat,
                   scatter = df_scatter, output_dir = file_path_main))
  }
  list(add_cohort = add_cohort, finish = finish, output_dir = file_path_main)
}

