  .safe_colname <- function(x) {
    x <- gsub("[^A-Za-z0-9_]+", "_", as.character(x))
    x <- gsub("_+", "_", x)
    x <- gsub("^_|_$", "", x)
    x
  }

  compute_marker_module_scores <- function(expr_mat, marker_list) {
    if (is.null(marker_list) || length(marker_list) == 0) {
      return(data.frame(row.names = colnames(expr_mat)))
    }

    gene_names <- rownames(expr_mat)
    gene_names_upper <- toupper(gene_names)

    module_score_df <- data.frame(
      sample = colnames(expr_mat),
      stringsAsFactors = FALSE
    )
    rownames(module_score_df) <- module_score_df$sample

    for (module_name in names(marker_list)) {
      markers_cur <- unique(toupper(as.character(marker_list[[module_name]])))
      markers_cur <- markers_cur[!is.na(markers_cur) & markers_cur != ""]

      row_idx <- which(gene_names_upper %in% markers_cur)
      score_col <- paste0(.safe_colname(module_name), "_module_score")

      message(
        "  -> ", module_name, ": ",
        length(unique(gene_names_upper[row_idx])), "/", length(markers_cur),
        " marker genes detected"
      )

      if (length(row_idx) == 0) {
        module_score_df[[score_col]] <- NA_real_
      } else {
        module_score_df[[score_col]] <- as.numeric(
          colMeans(expr_mat[row_idx, , drop = FALSE], na.rm = TRUE)
        )
      }
    }

    module_score_df$sample <- NULL
    module_score_df
  }

  ## Add usable module-score columns to a survival data.frame by sample ID.
  add_module_scores_to_df <- function(df, module_score_df) {
    if (is.null(module_score_df) || ncol(module_score_df) == 0) return(df)
    if (!("sample" %in% colnames(df))) return(df)

    module_score_df <- as.data.frame(module_score_df)
    module_use <- module_score_df[df$sample, , drop = FALSE]

    for (score_col in colnames(module_use)) {
      x <- suppressWarnings(as.numeric(module_use[[score_col]]))
      x_sd <- stats::sd(x, na.rm = TRUE)

      ## Skip unavailable or non-informative module scores to avoid Cox failures.
      if (sum(is.finite(x)) < 10) next
      if (!is.finite(x_sd) || x_sd == 0) next

      df[[score_col]] <- x
    }

    df
  }

  ## Filter Cox covariates to avoid one-level factors or zero-variance numerics.
  filter_usable_covars <- function(df, candidate_covars) {
    candidate_covars <- candidate_covars[candidate_covars %in% colnames(df)]

    Filter(function(v) {
      x <- df[[v]]
      if (is.factor(x) || is.character(x)) {
        length(unique(stats::na.omit(as.character(x)))) >= 2
      } else {
        x <- suppressWarnings(as.numeric(x))
        x_sd <- stats::sd(x, na.rm = TRUE)
        sum(is.finite(x)) >= 2 && is.finite(x_sd) && x_sd > 0
      }
    }, candidate_covars)
  }

  ## Extract the LRT row from anova(fit_A, fit_AB, test = "LRT") robustly.
  extract_nested_lrt <- function(lrt_tab) {
    if (is.null(lrt_tab) || nrow(lrt_tab) < 2) {
      return(list(chisq = NA_real_, df = NA_real_, pvalue = NA_real_))
    }

    lrt_df <- as.data.frame(lrt_tab)
    lrt_row <- lrt_df[nrow(lrt_df), , drop = FALSE]

    chisq_col <- intersect(c("Chisq", "Chi-square", "ChiSq"), colnames(lrt_df))
    df_col <- intersect(c("Df", "df", "DF"), colnames(lrt_df))
    p_col <- grep("Pr|P", colnames(lrt_df), value = TRUE)

    chisq_val <- if (length(chisq_col) > 0) as.numeric(lrt_row[[chisq_col[1]]]) else NA_real_
    df_val <- if (length(df_col) > 0) as.numeric(lrt_row[[df_col[1]]]) else NA_real_
    p_val <- if (length(p_col) > 0) as.numeric(lrt_row[[p_col[1]]]) else NA_real_

    list(chisq = chisq_val, df = df_val, pvalue = p_val)
  }

  choose_score_threshold <- function(score_vec) {
    score_vec <- as.numeric(score_vec)
    score_vec <- score_vec[is.finite(score_vec)]
  
    if (length(score_vec) == 0) return(NA_real_)
  
    threshold_score <- median(score_vec, na.rm = TRUE)
  
    if (threshold_score > 0.7) {
      threshold_score <- quantile(score_vec, 0.25, na.rm = TRUE)
    }
  
    return(threshold_score)
  }
