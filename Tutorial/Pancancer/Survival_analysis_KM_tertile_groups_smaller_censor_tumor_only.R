add_covariate <- function(df, coldata_use, varname, as_factor = FALSE) {
  if (!(varname %in% colnames(coldata_use))) return(df)

  x <- coldata_use[[varname]]
  if (all(is.na(x))) return(df)

  if (as_factor) {
    x <- as.factor(x)
    if (length(unique(stats::na.omit(x))) < 2) return(df)
  } else {
    x <- suppressWarnings(as.numeric(x))
    if (all(is.na(x))) return(df)
  }

  df[[varname]] <- x
  df
}

## =========================================================
## Standardize continuous MI abundance within the model analysis set.
## The Cox hazard ratio is per one-standard-deviation increase.
## =========================================================
scale_score_for_cox <- function(score_vec) {
  score_vec <- as.numeric(score_vec)
  score_sd <- stats::sd(score_vec, na.rm = TRUE)
  if (!is.finite(score_sd) || score_sd == 0) {
    return(rep(NA_real_, length(score_vec)))
  }
  as.numeric(scale(score_vec))
}

## =========================================================
## Kaplan-Meier curves for score tertiles with sample-count labels.
## Log-rank P compares groups; adjusted HR/Wald P use continuous MI abundance.
## =========================================================

## =========================================================
## Assign score tertiles using type-7 quantiles.
## Low: score <= q1; Mid: q1 < score <= q2; High: score > q2.
## Ties can produce unequal group sizes; coincident cutoffs leave groups missing.
## =========================================================
assign_score_tertile_group <- function(score_vec) {
  score_vec <- as.numeric(score_vec)
  group <- rep(NA_character_, length(score_vec))

  if (sum(is.finite(score_vec)) < 3) {
    return(factor(group, levels = c("Low", "Mid", "High")))
  }

  qs <- stats::quantile(
    score_vec,
    probs = c(1/3, 2/3),
    na.rm = TRUE,
    names = FALSE,
    type = 7
  )

  q1 <- qs[1]
  q2 <- qs[2]

  if (!is.finite(q1) || !is.finite(q2) || q1 == q2) {
    return(factor(group, levels = c("Low", "Mid", "High")))
  }

  group[is.finite(score_vec) & score_vec <= q1] <- "Low"
  group[is.finite(score_vec) & score_vec >  q1 & score_vec <= q2] <- "Mid"
  group[is.finite(score_vec) & score_vec >  q2] <- "High"

  factor(group, levels = c("Low", "Mid", "High"))
}

