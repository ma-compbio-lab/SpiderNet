  ## =========================================================
  ## Helper: find and add tumor purity covariate
  ## =========================================================
  find_tumor_purity_column <- function(coldata_use,
                                       candidate_cols = tumor_purity_candidate_cols,
                                       min_nonmissing = 10) {
    if (is.null(coldata_use) || ncol(coldata_use) == 0) {
      return(NA_character_)
    }

    col_names <- colnames(coldata_use)

    ## First try explicitly provided candidate names, then any column name
    ## containing "purity", "absolute" or exact/near-exact "CPE".
    candidate_existing <- intersect(candidate_cols, col_names)

    pattern_cols <- unique(c(
      grep("purity", col_names, ignore.case = TRUE, value = TRUE),
      grep("absolute", col_names, ignore.case = TRUE, value = TRUE),
      grep("^CPE$|_CPE$|\\.CPE$", col_names, ignore.case = TRUE, value = TRUE)
    ))

    candidate_existing <- unique(c(candidate_existing, pattern_cols))

    if (length(candidate_existing) == 0) {
      return(NA_character_)
    }

    for (col_cur in candidate_existing) {
      x <- suppressWarnings(as.numeric(coldata_use[[col_cur]]))
      x_sd <- stats::sd(x, na.rm = TRUE)

      if (sum(is.finite(x)) >= min_nonmissing &&
          is.finite(x_sd) && x_sd > 0) {
        return(col_cur)
      }
    }

    NA_character_
  }

  summarize_tumor_purity_source <- function(project_cur, coldata_use,
                                            if_add = If_add_tumor_purity,
                                            source_col = NA_character_) {
    if (!isTRUE(if_add)) {
      return(data.frame(
        project = project_cur,
        If_add_tumor_purity = FALSE,
        tumor_purity_source_col = NA_character_,
        n_nonmissing = NA_integer_,
        mean_tumor_purity = NA_real_,
        sd_tumor_purity = NA_real_,
        stringsAsFactors = FALSE,
        check.names = FALSE
      ))
    }

    if (is.na(source_col) || !(source_col %in% colnames(coldata_use))) {
      return(data.frame(
        project = project_cur,
        If_add_tumor_purity = TRUE,
        tumor_purity_source_col = NA_character_,
        n_nonmissing = 0L,
        mean_tumor_purity = NA_real_,
        sd_tumor_purity = NA_real_,
        stringsAsFactors = FALSE,
        check.names = FALSE
      ))
    }

    x <- suppressWarnings(as.numeric(coldata_use[[source_col]]))

    data.frame(
      project = project_cur,
      If_add_tumor_purity = TRUE,
      tumor_purity_source_col = source_col,
      n_nonmissing = sum(is.finite(x)),
      mean_tumor_purity = mean(x, na.rm = TRUE),
      sd_tumor_purity = stats::sd(x, na.rm = TRUE),
      stringsAsFactors = FALSE,
      check.names = FALSE
    )
  }

  add_tumor_purity_covariate <- function(df, coldata_use,
                                         if_add = If_add_tumor_purity,
                                         out_col = tumor_purity_covariate_name,
                                         source_col = NULL) {
    if (!isTRUE(if_add)) {
      return(df)
    }

    if (is.null(source_col)) {
      source_col <- find_tumor_purity_column(coldata_use)
    }

    if (is.na(source_col) || !(source_col %in% colnames(coldata_use))) {
      return(df)
    }

    if (nrow(coldata_use) != nrow(df)) {
      if ("sample" %in% colnames(df) && all(df$sample %in% rownames(coldata_use))) {
        coldata_use <- coldata_use[df$sample, , drop = FALSE]
      } else {
        stop("Cannot safely align tumor purity covariate to survival dataframe.")
      }
    }

    x <- suppressWarnings(as.numeric(coldata_use[[source_col]]))
    x_sd <- stats::sd(x, na.rm = TRUE)

    if (sum(is.finite(x)) < 10 || !is.finite(x_sd) || x_sd == 0) {
      message("  -> Tumor-purity column found (", source_col, ") but it is not usable; continuing without tumor purity.")
      return(df)
    }

    df[[out_col]] <- x
    df
  }

