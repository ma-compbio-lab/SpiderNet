    def _safe_column_max_normalize(arr):
        arr = np.asarray(arr, dtype=float)
        if arr.ndim == 1:
            max_val = np.nanmax(arr)
            if (not np.isfinite(max_val)) or max_val <= 0:
                return np.zeros_like(arr, dtype=float)
            return arr / max_val

        arr_norm = arr.copy()
        col_max = np.nanmax(arr_norm, axis=0)
        col_max[(~np.isfinite(col_max)) | (col_max <= 0)] = 1.0
        arr_norm = arr_norm / col_max
        arr_norm[~np.isfinite(arr_norm)] = 0.0
        return arr_norm


