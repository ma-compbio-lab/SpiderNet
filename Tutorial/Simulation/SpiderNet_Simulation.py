def Ligand_Receptor_gene_extraction(cellchat_ligand_receptor_filedir, adata):
    cellchat_ligand_receptor = pd.read_csv(cellchat_ligand_receptor_filedir, header=None)
    cellchat_ligand_receptor = np.array(cellchat_ligand_receptor.iloc[:, 0]).tolist()

    for i in range(len(cellchat_ligand_receptor)):
        cellchat_ligand_receptor[i] = cellchat_ligand_receptor[i].replace(" ", "")

    Ligand_list = [cellchat_ligand_receptor[i].split("-")[0] for i in range(len(cellchat_ligand_receptor))]
    Ligand_list_unique = np.unique(np.array(Ligand_list)).tolist()

    Receptor_list0 = [cellchat_ligand_receptor[i].split("-")[1] for i in range(len(cellchat_ligand_receptor))]
    Receptor_list = []
    for j in range(len(Receptor_list0)):
        if "+" in Receptor_list0[j]:
            Receptor_list.append(Receptor_list0[j].replace("(", "").replace(")", "").split("+"))
        else:
            Receptor_list.append([Receptor_list0[j]])

    Receptor_list_unique = np.unique(np.array(list(chain.from_iterable(Receptor_list)))).tolist()
    print("The Ligand-encoding genes in data:", np.sum(np.isin(adata.var_names, Ligand_list_unique)))
    print("The Receptor-encoding genes in data:", np.sum(np.isin(adata.var_names, Receptor_list_unique)))

    Ligand_output = list(adata.var_names[np.isin(adata.var_names, Ligand_list_unique)])
    Receptor_output = list(adata.var_names[np.isin(adata.var_names, Receptor_list_unique)])

    Ligand_list_extend = []
    for i in range(len(Ligand_list)):
        Ligand_list_extend.extend([Ligand_list[i]] * len(Receptor_list[i]))

    Receptor_list_extend = list(chain.from_iterable(Receptor_list))
    LR_both_index = np.where(
        np.isin(Ligand_list_extend, adata.var_names) * np.isin(Receptor_list_extend, adata.var_names)
    )[0]
    Ligand_list_extend = np.array(Ligand_list_extend)[LR_both_index]
    Receptor_list_extend = np.array(Receptor_list_extend)[LR_both_index]
    LR_list_extend = np.vstack((Ligand_list_extend, Receptor_list_extend)).T
    LR_list_extend = LR_list_extend[np.where(~(LR_list_extend[:, 0] == LR_list_extend[:, 1]))[0], :]
    LR_list_extend_unique = np.unique(LR_list_extend, axis=0)

    return Ligand_output, Receptor_output, LR_list_extend_unique


def top_k_elements_indices(tensor, K):
    if K > tensor.size:
        raise ValueError("K cannot be larger than the total number of elements in the tensor.")

    flat_indices = np.argpartition(tensor.flatten(), -K)[-K:]
    top_k_values = tensor.flatten()[flat_indices]
    top_k_coords = np.unravel_index(flat_indices, tensor.shape)

    sorted_indices = np.argsort(top_k_values)[::-1]
    top_k_values = top_k_values[sorted_indices]
    top_k_coords = [coords[sorted_indices] for coords in top_k_coords]
    top_k_indices = list(zip(*top_k_coords))

    return top_k_values, top_k_indices


def cosine_similarity(A, B):
    dot_product = np.dot(A.T, B)
    norm_A = np.linalg.norm(A, axis=0)
    norm_B = np.linalg.norm(B, axis=0)
    similarity = dot_product / (norm_A[:, np.newaxis] * norm_B[np.newaxis, :])
    return similarity


def spearman_corr_matrix(A, B):
    A_ranked = np.apply_along_axis(rankdata, 1, A)
    B_ranked = np.apply_along_axis(rankdata, 1, B)

    A_centered = A_ranked - A_ranked.mean(axis=1, keepdims=True)
    B_centered = B_ranked - B_ranked.mean(axis=1, keepdims=True)

    A_norm = A_centered / np.linalg.norm(A_centered, axis=1, keepdims=True)
    B_norm = B_centered / np.linalg.norm(B_centered, axis=1, keepdims=True)

    spearman_matrix = np.dot(A_norm, B_norm.T)
    return spearman_matrix


def compute_coexpression_simple(edge_index, exp_use_sparse):
    edge_index_hstack = edge_index[:, 0]
    edge_index_hstack_reversed = edge_index[:, 1]

    exp_target = exp_use_sparse
    selector_matrix = sp.csr_matrix(
        (np.ones_like(edge_index_hstack), (np.arange(len(edge_index_hstack)), edge_index_hstack)),
        shape=(len(edge_index_hstack), exp_target.shape[0]),
        dtype=np.int16,
    )
    exp_target_extend = selector_matrix.dot(exp_target)
    del selector_matrix, exp_target

    exp_neigh = exp_use_sparse
    selector_matrix = sp.csr_matrix(
        (np.ones_like(edge_index_hstack_reversed), (np.arange(len(edge_index_hstack_reversed)), edge_index_hstack_reversed)),
        shape=(len(edge_index_hstack_reversed), exp_neigh.shape[0]),
        dtype=np.int16,
    )
    exp_neigh_extend = selector_matrix.dot(exp_neigh)
    del selector_matrix, exp_neigh

    exp_target_dense = exp_target_extend.toarray() if sp.issparse(exp_target_extend) else exp_target_extend
    exp_neigh_dense = exp_neigh_extend.toarray() if sp.issparse(exp_neigh_extend) else exp_neigh_extend

    outer_product_list = []
    for i in range(exp_target_dense.shape[0]):
        outer_product = np.outer(exp_target_dense[i], exp_neigh_dense[i])
        outer_product_list.append(outer_product.flatten())

    exp_coexpression_extend = np.vstack(outer_product_list)
    exp_coexpression_extend = np.sqrt(exp_coexpression_extend)
    exp_coexpression_extend = exp_coexpression_extend[:, np.sum(exp_coexpression_extend, axis=0) > 0]
    return exp_coexpression_extend


