    adata = _make_simulation_adata(
        exp_nor_pd=exp_nor_pd,
        spatial_location=spatial_location,
        cellmeta_data=cellmeta_data,
        setting_name=Setting_cur,
        experiment_index=experiment_index,
    )

    spidernet_data_cpu = _safe_to_cpu_data(SpiderNet_data_pyg)
    lr_array = np.asarray(LR_list).astype(str)
    genenames_train = np.asarray(exp_nor_pd.columns).astype(str)
    cellclass_unique = np.sort(cellmeta_data["Celltype"].astype(str).unique())
    batch_cell = np.zeros(adata.n_obs, dtype=np.int64)
    batch_cell_unique = np.asarray([sample_name])

    _write_pickle([spidernet_data_cpu], processed_data_dir / "SpiderNet_data_pyg_list.pkl")
    _write_pickle(lr_array, processed_data_dir / "LR_list.pkl")

    # The HGSOC bundle includes these database-derived LR metadata files.
    # The simulation LR list is synthetic, so we provide minimal compatible
    # placeholders that preserve the same file contract.
    _write_pickle(lr_array, processed_data_dir / "LR_list_cellchatdb.pkl")
    lr_meta = pd.DataFrame({
        "ligand": lr_array[:, 0] if lr_array.size else [],
        "receptor": lr_array[:, 1] if lr_array.size else [],
        "pathway_name": ["Simulation"] * lr_array.shape[0],
    })
    _write_pickle(lr_meta, processed_data_dir / "LR_meta_cellchatdb.pkl")

    _write_pickle(batch_cell_unique, processed_data_dir / "batch_cell_unique.pkl")
    _write_pickle(batch_cell, processed_data_dir / "batch_cell.pkl")
    _write_pickle(genenames_train, processed_data_dir / "genenames_train.pkl")
    _write_pickle([adata], processed_data_dir / "adata_list.pkl")
    _write_pickle(cellclass_unique, processed_data_dir / "cellclass_unique.pkl")
    adata.write_h5ad(processed_data_dir / "adata_all.h5ad")

    metadata_sample = pd.DataFrame({
        "sample_name": [sample_name],
        "setting": [Setting_cur],
        "experiment": [experiment_index],
        "n_cells": [adata.n_obs],
        "n_genes": [adata.n_vars],
        "n_lr_pairs": [lr_array.shape[0]],
    })
    metadata_sample.to_csv(processed_data_dir / "metadata_sample.csv", index=False)

    bundle_summary = {
        "dataset": "Simulation",
        "setting": Setting_cur,
        "experiment": int(experiment_index),
        "n_batches": 1,
        "n_cells": int(adata.n_obs),
        "n_genes": int(adata.n_vars),
        "n_lr_pairs": int(lr_array.shape[0]),
    }
    with open(processed_data_dir / "bundle_summary.json", "w", encoding="utf-8") as handle:
        json.dump(bundle_summary, handle, indent=2)

    return processed_data_dir


