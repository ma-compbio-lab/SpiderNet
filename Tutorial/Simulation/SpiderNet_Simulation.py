def _write_pickle(obj, path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "wb") as handle:
        pickle.dump(obj, handle)


def _safe_to_cpu_data(data):
    """Return a CPU copy of a PyG Data object for portable processed-bundle IO."""
    try:
        return data.clone().cpu()
    except Exception:
        return data.to("cpu")


def _make_simulation_adata(exp_nor_pd, spatial_location, cellmeta_data, setting_name, experiment_index):
    """Build an AnnData object matching the fields expected by SpiderNet IO/API."""
    adata = sc.AnnData(X=exp_nor_pd.values.astype(np.float32))
    adata.obs_names = exp_nor_pd.index.astype(str)
    adata.var_names = exp_nor_pd.columns.astype(str)
    adata.obsm["spatial"] = np.asarray(spatial_location.values, dtype=np.float32)

    if "Celltype" not in cellmeta_data.columns:
        raise KeyError("cellmeta_data must contain a 'Celltype' column for simulation training.")

    if pd.Index(exp_nor_pd.index).isin(cellmeta_data.index).all():
        celltype = cellmeta_data.loc[exp_nor_pd.index, "Celltype"].astype(str).values
    else:
        # Fall back to row order, matching the original simulation script.
        celltype = cellmeta_data["Celltype"].astype(str).values
        if celltype.shape[0] != exp_nor_pd.shape[0]:
            raise ValueError(
                "cellmeta_data does not align with gene_exp.csv by index or row order."
            )

    adata.obs["Celltype"] = celltype
    adata.obs["cell_type"] = celltype
    adata.obs["cell.type"] = celltype
    adata.obs["cell_class"] = celltype
    adata.obs["sample_name"] = f"{setting_name}_Experiment_{experiment_index}"
    adata.obs["batch"] = f"{setting_name}_Experiment_{experiment_index}"
    adata.obs["xcoord"] = adata.obsm["spatial"][:, 0]
    adata.obs["ycoord"] = adata.obsm["spatial"][:, 1]
    return adata


