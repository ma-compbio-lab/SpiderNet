def _load_sccchain_scores_to_reference_edges_export(sc_csv_path, edge_index):
    sc_df = pd.read_csv(sc_csv_path)
    if sc_df.shape[1] < 3:
        raise ValueError(f"Unexpected ScCChain CSV format: {sc_csv_path}")

    sender_col = sc_df.columns[0]
    receiver_col = sc_df.columns[1]
    program_cols = sc_df.columns.tolist()[2:]

    sc_df = sc_df.rename(columns={
        sender_col: "sender_index",
        receiver_col: "receiver_index",
    }).copy()

    sc_df["sender_index"] = pd.to_numeric(sc_df["sender_index"], errors="coerce").astype("Int64")
    sc_df["receiver_index"] = pd.to_numeric(sc_df["receiver_index"], errors="coerce").astype("Int64")
    sc_df = sc_df.dropna(subset=["sender_index", "receiver_index"]).copy()
    sc_df["sender_index"] = sc_df["sender_index"].astype(np.int64)
    sc_df["receiver_index"] = sc_df["receiver_index"].astype(np.int64)

    # Julia output is 1-based.
    sc_df["sender_index"] -= 1
    sc_df["receiver_index"] -= 1

    edge_index_df = pd.DataFrame(edge_index, columns=["sender_index", "receiver_index"])
    edge_mi = pd.MultiIndex.from_frame(edge_index_df[["sender_index", "receiver_index"]])

    sc_df = sc_df.drop_duplicates(subset=["sender_index", "receiver_index"], keep="first").copy()
    sc_df_indexed = sc_df.set_index(["sender_index", "receiver_index"])[program_cols]

    aligned_scores = (
        sc_df_indexed.reindex(edge_mi)
        .fillna(0.0)
        .to_numpy(dtype=np.float32, copy=False)
    )
    return aligned_scores


def _compute_commot_scores_export(SpiderNet_data_pyg, edge_index_np):
    exp_nor = SpiderNet_data_pyg["x"].to("cpu").detach().numpy()
    gene_names = SpiderNet_data_pyg["genenames"]
    cell_names = SpiderNet_data_pyg["cellnames"]
    spatial_pos = SpiderNet_data_pyg["pos"].to("cpu").detach().numpy()

    adata_commot = sc.AnnData(
        X=exp_nor,
        obs=pd.DataFrame(index=cell_names),
        var=pd.DataFrame(index=gene_names),
    )
    adata_commot.obsm["spatial"] = spatial_pos

    LR = np.array([
        ["L1", "R1", "MI1_pathway"],
        ["L2", "R2", "MI1_pathway"],
        ["L3", "R3", "MI1_pathway"],
        ["L4", "R4", "MI1_pathway"],
        ["L5", "R5", "MI1_pathway"],
        ["L6", "R6", "MI1_pathway"],
        ["L7", "R7", "MI1_pathway"],
        ["L8", "R8", "MI1_pathway"],
        ["L9", "R9", "MI1_pathway"],
        ["L10", "R10", "MI2_pathway"],
        ["L11", "R11", "MI2_pathway"],
        ["L12", "R12", "MI2_pathway"],
        ["L13", "R13", "MI2_pathway"],
        ["L14", "R14", "MI2_pathway"],
        ["L15", "R15", "MI2_pathway"],
        ["L16", "R16", "MI2_pathway"],
        ["L17", "R17", "MI2_pathway"],
        ["L18", "R18", "MI2_pathway"],
        ["L19", "R19", "MI2_pathway"],
        ["L20", "R20", "MI2_pathway"],
    ], dtype=str)
    df_ligrec = pd.DataFrame(LR)

    spatial_coords = np.asarray(adata_commot.obsm["spatial"], dtype=np.float32)
    n = spatial_coords.shape[0]
    k = 10
    if n <= k:
        raise ValueError("Not enough cells to build the COMMOT distance threshold.")

    nn = NearestNeighbors(n_neighbors=k + 1, algorithm="auto", metric="euclidean")
    nn.fit(spatial_coords)
    dists, _ = nn.kneighbors(spatial_coords, return_distance=True)
    dists_k = dists[:, 1:]
    dist_vec = dists_k.mean(axis=1).astype(np.float32)
    dist_median = float(np.median(dist_vec[~np.isnan(dist_vec)]))

    ct.tl.spatial_communication(
        adata_commot,
        database_name="cellchat",
        df_ligrec=df_ligrec,
        dis_thr=dist_median,
        heteromeric=True,
        pathway_sum=True,
        cot_nitermax=2000,
    )

    factor_commot = np.vstack([
        adata_commot.obsp["commot-cellchat-MI1_pathway"].toarray()[edge_index_np[:, 0], edge_index_np[:, 1]],
        adata_commot.obsp["commot-cellchat-MI2_pathway"].toarray()[edge_index_np[:, 0], edge_index_np[:, 1]],
    ]).T
    return _safe_column_max_normalize_export(factor_commot)


def _get_best_component_scores_export(factor_matrix, edge_MI1, edge_MI2, mi_index):
    factor_matrix = np.asarray(factor_matrix, dtype=float)
    if factor_matrix.ndim == 1:
        return _safe_column_max_normalize_export(factor_matrix)

    if factor_matrix.shape[1] == 0:
        return np.zeros(factor_matrix.shape[0], dtype=float)

    ref_edges = edge_MI1 if mi_index == 0 else edge_MI2
    if ref_edges.size == 0:
        best_idx = 0
    else:
        best_idx = int(np.argmax(np.mean(factor_matrix[ref_edges, :], axis=0)))
    scores = factor_matrix[:, best_idx]
    return _safe_column_max_normalize_export(scores)


