def _result_array(results, aliases, required=True):
    for key in aliases:
        if key in results:
            value = results[key]
            if torch.is_tensor(value):
                return value.detach().cpu().numpy()
            return np.asarray(value)
    if required:
        raise KeyError(f"None of the result keys were found: {aliases}")
    return None


def _model_parameter_array(model, aliases, required=False):
    if not hasattr(model, "named_parameters"):
        if required:
            raise AttributeError("Model has no named_parameters method.")
        return None

    for name, param in model.named_parameters():
        for alias in aliases:
            if name == alias or name.endswith(alias) or alias in name:
                arr = param.detach().cpu().numpy()
                # Loading parameters are constrained as non-negative in SpiderNet.
                return np.maximum(arr, 0)

    if required:
        raise KeyError(f"None of the model parameter aliases were found: {aliases}")
    return None


def _result_or_model_array(results, model, result_aliases, model_aliases, required=True):
    arr = _result_array(results, result_aliases, required=False)
    if arr is not None:
        return arr
    arr = _model_parameter_array(model, model_aliases, required=False)
    if arr is not None:
        return arr
    if required:
        raise KeyError(
            "Could not locate output in normalized inference results or model parameters. "
            f"Result aliases: {result_aliases}; model aliases: {model_aliases}"
        )
    return None


